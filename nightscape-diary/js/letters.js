/**
 * 手紙の冒頭：今日の天気と月（時刻は入れない。時刻はホームの「今夜の空」で見られる）
 * 天気を取得できていない日は、天気には触れない。手動設定のときは手動設定と明記する。
 */
const hmOf = iso => { const d = new Date(iso); return `${d.getHours()}:${String(d.getMinutes()).padStart(2, '0')}`; };
export function openingLine(s) {
  const w = s.weather;
  const parts = [];
  if (w && s.source === 'open-meteo' && w.stale) parts.push(`${hmOf(w.fetchedAt)}ごろの${s.city}は${w.label}でした（最新の天気は取得できていません）。`);
  else if (w && s.source === 'open-meteo') parts.push(`今日の${s.city}は${w.label}${w.temp != null ? `、気温は${w.temp}℃ほど` : ''}です。`);
  else if (w && s.source === 'manual') parts.push(`（天気は手動設定：${w.label}）`);
  if (s.moon.visible) parts.push(`月齢${s.moon.age}の${s.moon.name}が出る日です。`);
  if (!parts.length) parts.push('今日も、帰り道の景色に少しだけ目を向けてみませんか。');
  return parts.join('');
}

function hashStr(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

/**
 * 今日の手紙を選ぶ。
 *  - 天気：分かっている日はその天気に合う手紙。分からない日は、天気を前提にした手紙を出さない
 *  - 時間帯：暗くなってから開いた日は、夕方の空を見る手紙を出さない（時刻は文面に書かない）
 *  - 月：見える日だけ月の手紙。明るい月が前提の手紙は満月の前後だけ
 *  - 重複：直近21日に届いた手紙と、直近2日と同じテーマはなるべく避ける
 *  - 代替：条件に合う手紙が少ないときは、条件をゆるめて選ぶ
 * history: これまでに届いた手紙 [{ date, id }]（新しい順）
 */
export function pickLetter(dateKey, s, bucket, history = []) {
  const cond = s.weather ? s.weather.cond : null;
  const ids = history.map(h => h.id);
  const lastThemes = history.slice(0, 2).map(h => (letterById(h.id) || {}).theme);
  const weatherOk = l => {
    if (!l.weather) return true;
    if (cond) return l.weather.includes(cond);
    return l.weather.includes('clear') && l.weather.includes('cloudy');
  };
  const timeOk = l => l.when !== 'dusk' || bucket !== 'night';
  const moonOk = l => !l.moon || (s.moon.visible && (!l.moonBright || (s.moon.age >= 11 && s.moon.age <= 18)));
  const base = LETTERS.filter(l => weatherOk(l) && timeOk(l) && moonOk(l));
  let pool = base;
  if (cond === 'rain' || cond === 'after-rain') {
    const special = base.filter(l => l.weather && l.weather.includes(cond) && l.weather.length <= 2);
    if (special.length) pool = special;
  }
  if (s.moon.visible && s.moon.age >= 13.5 && s.moon.age < 16.5 && cond !== 'rain') {
    const m = pool.filter(l => l.theme === '月');
    if (m.length && hashStr(dateKey) % 2 === 0) pool = m;
  }
  const h = hashStr(dateKey + (cond || '') + bucket);
  const tries = [
    pool.filter(l => !ids.slice(0, 21).includes(l.id) && !lastThemes.includes(l.theme)),
    pool.filter(l => !ids.slice(0, 7).includes(l.id)),
    base.filter(l => !ids.slice(0, 3).includes(l.id)),
    LETTERS.filter(l => !l.weather && !l.moon),
  ];
  const list = tries.find(t => t.length >= 2) || tries.find(t => t.length) || LETTERS;
  return list[h % list.length];
}
